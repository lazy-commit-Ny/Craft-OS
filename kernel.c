void draw_char(int x, int y, char c, uint8_t color) {
    if (c < 32 || c > 127) return;
    const uint8_t* glyph = font8x8[c - 32];
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            if (glyph[row] & (1 << (7 - col))) put_pixel(x + col, y + row, color);
        }
    }
}

void draw_string(int x, int y, const char* str, uint8_t color) {
    for (int i = 0; str[i] != '\0'; i++) draw_char(x + i * 8, y, str[i], color);
}

#define NE2000_BASE 0x300
int wifi_enabled = 1;
int wifi_connected_idx = 0;
int wifi_menu_open = 0;
int nic_detected = 0;

const char* wifi_ssids[3] = { "MyHome-WiFi-6E", "Star_Cafe_Free", "My_iPhone_17" };

void init_network_hardware() {
    uint8_t val = inb(NE2000_BASE + 0x1F);
    outb(NE2000_BASE + 0x1F, val);
    outb(NE2000_BASE + 0x00, 0x21);
    if (inb(NE2000_BASE + 0x00) != 0xFF) nic_detected = 1;
}

void send_wifi_ping_frame() {
    if (!nic_detected || !wifi_enabled) return;
    outb(NE2000_BASE + 0x00, 0x22);
    outb(NE2000_BASE + 0x05, 60);
    outb(NE2000_BASE + 0x06, 0);
    outb(NE2000_BASE + 0x00, 0x26);
}

void draw_wifi_icon(int x, int y, uint8_t color) {
    if (!wifi_enabled) { draw_string(x, y, "X", 4); return; }
    for (int dx = -4; dx <= 4; dx++) put_pixel(x + dx, y + 1, color);
    for (int dx = -2; dx <= 2; dx++) put_pixel(x + dx, y + 3, color);
    put_pixel(x, y + 5, color);
    put_pixel(x, y + 6, color);
}

void draw_cursor(int x, int y) {
    for (int i = 0; i < 8; i++) {
        for (int j = 0; j <= i; j++) {
            uint8_t col = (j == 0 || j == i || i == 7) ? 0 : 15;
            put_pixel(x + j, y + i, col);
        }
    }
}

