const char scancode_to_ascii[] = {
    0, 27, '1', '2', '3', '4', '5', '6', '7', '8', '9', '0', '-', '=', '\b',
    '\t', 'q', 'w', 'e', 'r', 't', 'y', 'u', 'i', 'o', 'p', '[', ']', '\n',
    0, 'a', 's', 'd', 'f', 'g', 'h', 'j', 'k', 'l', ';', '\'', '`',
    0, '\\', 'z', 'x', 'c', 'v', 'b', 'n', 'm', ',', '.', '/', 0,
    '*', 0, ' '
};

void kernel_main(void) {
    set_vga_mode_13h();
    init_network_hardware();
    init_mouse();

    const char* status_msg = "> Ready. Move Mouse or [W]";
    int prev_click = 0;
    draw_macos_desktop(status_msg);

    while (1) {
        int need_redraw = 0;

        if (poll_mouse()) {
            need_redraw = 1;
            if (mouse_left_click && !prev_click) {
                if (mouse_y <= 12 && mouse_x >= 245 && mouse_x <= 268) {
                    wifi_menu_open = !wifi_menu_open;
                    status_msg = wifi_menu_open ? "> Wi-Fi Menu Opened" : "> Wi-Fi Menu Closed";
                }
                else if (wifi_menu_open && mouse_x >= 175 && mouse_x <= 313) {
                    if (mouse_y >= 18 && mouse_y <= 30) {
                        wifi_enabled = !wifi_enabled;
                        status_msg = wifi_enabled ? "> Wi-Fi Turned ON" : "> Wi-Fi Turned OFF";
                    } else if (mouse_y >= 34 && mouse_y <= 47) {
                        wifi_enabled = 1; wifi_connected_idx = 0;
                        status_msg = "> Joined MyHome-WiFi-6E";
                    } else if (mouse_y >= 48 && mouse_y <= 61) {
                        wifi_enabled = 1; wifi_connected_idx = 1;
                        status_msg = "> Joined Star_Cafe_Free";
                    } else if (mouse_y >= 62 && mouse_y <= 75) {
                        wifi_enabled = 1; wifi_connected_idx = 2;
                        status_msg = "> Joined My_iPhone_17";
                    }
                }
            }
            prev_click = mouse_left_click;
        }

        uint8_t status = inb(0x64);
        if ((status & 0x01) && !(status & 0x20)) {
            uint8_t scancode = inb(0x60);
            if (!(scancode & 0x80) && scancode < sizeof(scancode_to_ascii)) {
                char c = scancode_to_ascii[scancode];
                if (c == 'w' || c == 'W') { wifi_menu_open = !wifi_menu_open; need_redraw = 1; }
                else if (c == 't' || c == 'T') { wifi_enabled = !wifi_enabled; need_redraw = 1; }
                else if (c == '1') { wifi_enabled = 1; wifi_connected_idx = 0; status_msg = "> Joined MyHome-WiFi-6E"; need_redraw = 1; }
                else if (c == '2') { wifi_enabled = 1; wifi_connected_idx = 1; status_msg = "> Joined Star_Cafe_Free"; need_redraw = 1; }
                else if (c == '3') { wifi_enabled = 1; wifi_connected_idx = 2; status_msg = "> Joined My_iPhone_17"; need_redraw = 1; }
                else if (c == 'p' || c == 'P') {
                    if (wifi_enabled) { send_wifi_ping_frame(); status_msg = "> TX: 60B Packet Sent!"; }
                    else { status_msg = "> Err: Turn Wi-Fi ON first"; }
                    need_redraw = 1;
                }
            }
        }

        if (need_redraw) {
            draw_macos_desktop(status_msg);
        }
    }
}
