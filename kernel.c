static inline uint8_t inb(uint16_t port) {
    uint8_t ret;
    asm volatile ( "inb %1, %0" : "=a"(ret) : "Nd"(port) );
    return ret;
}

static inline void outb(uint16_t port, uint8_t val) {
    asm volatile ( "outb %0, %1" : : "a"(val), "Nd"(port) );
}

unsigned char* vga = (unsigned char*)0xA0000;
#define SCREEN_W 320
#define SCREEN_H 200

void set_vga_mode_13h() {
    unsigned char regs[] = {
        0x63,
        0x03, 0x01, 0x0F, 0x00, 0x0E,
        0x5F, 0x4F, 0x50, 0x82, 0x54, 0x80, 0xBF, 0x1F,
        0x00, 0x41, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x9C, 0x0E, 0x8F, 0x28, 0x40, 0x96, 0xB9, 0xA3, 0xFF,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x05, 0x0F, 0xFF,
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F,
        0x41, 0x00, 0x0F, 0x00, 0x00
    };
    unsigned char *p = regs;
    outb(0x3C2, *(p++));
    for (int i = 0; i < 5; i++) { outb(0x3C4, i); outb(0x3C5, *(p++)); }
    outb(0x3D4, 0x03); outb(0x3D5, inb(0x3D5) | 0x80);
    outb(0x3D4, 0x11); outb(0x3D5, inb(0x3D5) & ~0x80);
    regs[6 + 0x03] |= 0x80; regs[6 + 0x11] &= ~0x80;
    for (int i = 0; i < 25; i++) { outb(0x3D4, i); outb(0x3D5, *(p++)); }
    for (int i = 0; i < 9; i++) { outb(0x3CE, i); outb(0x3CF, *(p++)); }
    for (int i = 0; i < 21; i++) { (void)inb(0x3DA); outb(0x3C0, i); outb(0x3C0, *(p++)); }
    (void)inb(0x3DA); outb(0x3C0, 0x20);
}

void put_pixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < SCREEN_W && y >= 0 && y < SCREEN_H) {
        vga[y * SCREEN_W + x] = color;
    }
}

void fill_rect(int x, int y, int w, int h, uint8_t color) {
    for (int dy = 0; dy < h; dy++) {
        for (int dx = 0; dx < w; dx++) {
            put_pixel(x + dx, y + dy, color);
        }
    }
}

void fill_round_rect(int x, int y, int w, int h, uint8_t color) {
    fill_rect(x + 2, y, w - 4, h, color);
    fill_rect(x, y + 2, w, h - 4, color);
    fill_rect(x + 1, y + 1, w - 2, h - 2, color);
}

